/** snake_case an action name, keeping filler words (LLD transcription rule). */
function slugifyAction(name: string): string {
  return name
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '_')
    .replace(/^_+|_+$/g, '');
}

export function buildCatalog(modules: readonly ModuleSource[] = MODULES): CatalogEntry[] {
  const entries: CatalogEntry[] = [];
  for (const mod of modules) {
    if (mod.actions.length !== 10) {
      throw new Error(`${mod.code} (${mod.key}) has ${mod.actions.length} actions, expected 10`);
    }
    mod.actions.forEach((actionName, idx) => {
      const actionNum = String(idx + 1).padStart(2, '0');
      entries.push({
        id: `${mod.code}.A${actionNum}`,
        module: mod.key,
        moduleName: mod.name,
        name: actionName,
        slug: `${mod.key}.${slugifyAction(actionName)}`,
      });
    });
  }
  return entries;
}

function main(): void {
  if (MODULES.length !== 50) {
    throw new Error(`Expected 50 modules, got ${MODULES.length}`);
  }
  const catalog = buildCatalog();
  if (catalog.length !== 500) {
    throw new Error(`Expected 500 catalog entries, got ${catalog.length}`);
  }

  const here = dirname(fileURLToPath(import.meta.url));
  const outPath = resolve(here, '../server/src/catalog/catalog.json');
  writeFileSync(outPath, JSON.stringify(catalog, null, 2) + '\n', 'utf-8');
  console.log(`Wrote ${catalog.length} entries to ${outPath}`);
}

// Run only when executed directly (not when imported by tests).
if (import.meta.url === `file://${process.argv[1]}`) {
  main();
}
